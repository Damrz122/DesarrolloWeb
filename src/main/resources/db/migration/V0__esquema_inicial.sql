-- Esquema base para instalaciones nuevas. Las migraciones V1..V14 conservan
-- la evolución histórica del proyecto; por eso este archivo representa el
-- punto de partida anterior a V1 y no contiene datos de negocio.

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('ADMIN', 'CLIENTE')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(1000),
    precio NUMERIC(10,2) NOT NULL,
    stock INTEGER NOT NULL,
    imagen_url VARCHAR(500),
    categoria_id BIGINT NOT NULL REFERENCES categorias(id),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_productos_nombre_categoria UNIQUE (nombre, categoria_id)
);

CREATE TABLE carritos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id)
);

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    estado VARCHAR(30) NOT NULL CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'ENVIADO', 'ENTREGADO', 'CANCELADO')),
    total NUMERIC(10,2) NOT NULL,
    direccion_envio VARCHAR(255),
    telefono VARCHAR(30),
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE detalles_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL
);

CREATE TABLE pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedidos(id) ON DELETE CASCADE,
    metodo_pago VARCHAR(30) NOT NULL,
    estado_pago VARCHAR(30) NOT NULL CHECK (estado_pago IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'REEMBOLSADO')),
    monto NUMERIC(10,2) NOT NULL,
    codigo_transaccion VARCHAR(100),
    referencia_comprobante VARCHAR(100),
    fecha_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pagos_metodo_pago_check CHECK (metodo_pago IN ('TARJETA_CREDITO', 'TARJETA_DEBITO', 'YAPE', 'PLIN', 'TRANSFERENCIA_BANCARIA', 'PAGO_CONTRAENTREGA'))
);

CREATE TABLE envios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedidos(id) ON DELETE CASCADE,
    estado_envio VARCHAR(30) NOT NULL CHECK (estado_envio IN ('PREPARANDO', 'EN_TRANSITO', 'EN_DISTRIBUCION', 'ENTREGADO', 'DEVUELTO')),
    empresa_courier VARCHAR(100),
    numero_guia VARCHAR(100),
    direccion_destino VARCHAR(255) NOT NULL,
    fecha_despacho TIMESTAMP,
    fecha_estimada_entrega TIMESTAMP,
    fecha_entrega_real TIMESTAMP,
    observaciones VARCHAR(255)
);

CREATE TABLE conversaciones_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES usuarios(id),
    admin_id BIGINT REFERENCES usuarios(id),
    estado VARCHAR(30) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chat_mensajes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id BIGINT NOT NULL REFERENCES conversaciones_chat(id) ON DELETE CASCADE,
    remitente_id BIGINT NOT NULL REFERENCES usuarios(id),
    contenido VARCHAR(1000) NOT NULL,
    fecha_envio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE items_carrito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrito_id BIGINT NOT NULL REFERENCES carritos(id) ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    cantidad INTEGER NOT NULL
);

CREATE TABLE sitio_config (
    clave VARCHAR(80) PRIMARY KEY,
    valor VARCHAR(20000),
    actualizado TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
